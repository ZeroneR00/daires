/*
  Русское согласование числительных: 1 запись / 2 записи / 5 записей.
  Жило внутри HomeHero, пока было нужно одному месту; со счётчиком скрытых
  дорожек мест стало два, и копия правила в каждом — верный способ дать им
  разойтись. Файл, как lib/ui.ts, ничего не импортирует.

  Проверять надо и десятки, и сотни: 11-14 ведут себя как «много» вопреки
  своей последней цифре (11 записей, а не «11 запись»).
*/
export function plural(
  n: number,
  one: string,
  few: string,
  many: string,
): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}
