import type { MetadataRoute } from "next";
import { SITE_URL } from "@/lib/site";

/*
  Файловая конвенция Next: этот модуль отдаётся по адресу /robots.txt.

  **Админки в списке нет, и это не забывчивость.** robots.txt лежит по
  публичному адресу и читается кем угодно: строка `Disallow: /admin` объявила
  бы всему свету, что раздел существует, — ровно после того, как мы его
  прятали через notFound() и через generateMetadata(). Индексации админка не
  боится и без этого файла: у неё стоит `robots: { index: false }` в
  собственных метаданных, а краулер, который до неё дойдёт, получит 404.

  Остальные закрытые разделы никакой тайны не составляют — они есть на любом
  сайте с регистрацией, и прятать их не от кого. Смысл запрета здесь не
  в секретности, а в том, что краулеру там нечего индексировать: анониму все
  эти адреса отдают либо форму входа, либо редирект.

  `/search` закрыт по другой причине: у него бесконечное пространство
  query-параметров, и краулер может ходить по нему сколько угодно, каждый раз
  получая новый адрес с тем же содержимым.
*/
export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: "*",
      allow: "/",
      disallow: ["/api/", "/settings", "/new", "/post/", "/messages", "/friends", "/following", "/search"],
    },
    sitemap: `${SITE_URL}/sitemap.xml`,
    host: SITE_URL,
  };
}
