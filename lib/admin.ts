import { headers } from "next/headers";
import { notFound } from "next/navigation";
import { auth } from "@/lib/auth";

/*
  Всё про доступ в админку — и ничего про данные: читающие запросы админки
  живут отдельно (`lib/admin-queries.ts`), чтобы гард можно было звать из
  любого места, не таща за собой Prisma-выборки.

  Роль берём из сессии, а не своим `findUnique`. Довод: `session.cookieCache`
  в проекте не включён, поэтому `auth.api.getSession()` и так ходит в базу за
  строкой пользователя — отдельный запрос был бы вторым round-trip за тем же
  фактом, да ещё и через второй пул соединений (`lib/auth.ts` держит
  собственный `PrismaClient`).

  ВНИМАНИЕ, растяжка на будущее: если кто-то включит `session.cookieCache`,
  этот гард молча превратится в «роль по состоянию на N минут назад» —
  снятие роли перестанет действовать сразу. Включаешь кэш — переводи
  `getAdminSession()` на прямой запрос роли в базу.
*/

export const ADMIN_ROLE = "admin";

/**
 * Для Server Actions: `null` вместо броска — экшен сам решает, что вернуть
 * (тихо выйти или отдать `{ error }`).
 */
export async function getAdminSession() {
  const session = await auth.api.getSession({ headers: await headers() });
  return session?.user.role === ADMIN_ROLE ? session : null;
}

/**
 * Для страниц: не админ — значит страницы не существует.
 *
 * `notFound()`, а не `redirect("/login")`: редирект на форму входа — это
 * сообщение «тут что-то есть», а админка не должна палить своё существование.
 * Осознанная цена: админ с протухшей сессией увидит 404 вместо формы входа —
 * лечится обычным входом на `/login`.
 *
 * Границы этой маскировки, замерено 2026-09-09: `notFound()` из стримящейся
 * страницы отдаёт HTTP 200 с телом «Страница не найдена» — заголовки уже
 * ушли, статус менять поздно. Так ведут себя все гарды проекта (`/u/<нет>`,
 * `/post/<нет>/edit`, `/messages/<не друг>`), поэтому от них `/admin`
 * неотличим; а вот от вовсе несуществующего адреса (настоящий 404) —
 * отличим по статусу. То есть скрыт сам факт «тут есть закрытая страница»,
 * но не то, что маршрут `/admin` в приложении объявлен.
 */
export async function requireAdmin() {
  const session = await getAdminSession();
  if (!session) notFound();
  return session;
}
