/*
  Канонический адрес сайта одной строкой на весь проект.

  Своей переменной окружения под него нет намеренно: на проде
  `BETTER_AUTH_URL` — это он и есть, о чём написано комментарием в lib/auth.ts.
  Две переменные с одинаковым значением живут дружно ровно до первого переезда
  на свой домен, после которого одну поправят, а вторую забудут.

  Нужен тем, кто обязан выдать абсолютный адрес, но не видит входящего запроса:
  корневые метаданные (`metadataBase`), карта сайта и robots. RSS-фиды сюда
  не заглядывают и правильно делают — у них есть сам запрос, и origin они
  берут из него, что честнее любой константы.

  Фолбэк — для разработки; на проде переменная выставлена.
*/
export const SITE_URL = process.env.BETTER_AUTH_URL ?? "http://localhost:3000";

/*
  Имя сайта одной строкой. Нужно не только людям: в карточке ссылки это
  подпись над заголовком (`og:site_name`).

  Отдельная константа, а не литерал по месту, из-за того как Next склеивает
  метаданные: объекты вроде `openGraph` **не** сливаются с родительскими, а
  замещают их целиком. Значит каждая страница, объявившая свой `openGraph`,
  обязана заново указать и имя сайта, и локаль — иначе они просто пропадут
  (поймано на странице записи: og:site_name из корневого layout до неё
  не доезжал).
*/
export const SITE_NAME = "music·diary";
export const SITE_LOCALE = "ru_RU";
